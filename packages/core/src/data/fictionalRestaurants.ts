const ALL_DAYS: Weekday[] = [
  "monday",
  "tuesday",
  "wednesday",
  "thursday",
  "friday",
  "saturday",
  "sunday",
];

function hoursAgoIso(hours: number): string {
  return new Date(Date.now() - hours * 60 * 60 * 1000).toISOString();
}

function hoursFromNowIso(hours: number): string {
  return new Date(Date.now() + hours * 60 * 60 * 1000).toISOString();
}

function daysFromNowIso(days: number): string {
  return hoursFromNowIso(days * 24);
}

function openEveryDay(opensAt: string, closesAt: string, days: Weekday[] = ALL_DAYS): OpeningHours {
  return {
    intervals: days.map((day) => ({ day, opensAt, closesAt })),
    meta: { source: "fictional_demo", lastCheckedAt: hoursAgoIso(6), isVerified: true },
  };
}

let menuItemCounter = 0;
function menuItem(
  restaurantId: string,
  input: Omit<MenuItem, "id" | "restaurantId" | "meta" | "dietaryTags" | "isPopular"> &
    Partial<Pick<MenuItem, "dietaryTags" | "isPopular">>,
): MenuItem {
  menuItemCounter += 1;
  return {
    id: `menu_${restaurantId}_${menuItemCounter}`,
    restaurantId,
    dietaryTags: [],
    isPopular: false,
    meta: { source: "fictional_demo", lastCheckedAt: hoursAgoIso(12), isVerified: true },
    ...input,
  };
}

let offerCounter = 0;
function offer(restaurantId: string, input: Omit<Offer, "id" | "restaurantId" | "meta">): Offer {
  offerCounter += 1;
  return {
    id: `offer_${restaurantId}_${offerCounter}`,
    restaurantId,
    meta: { source: "fictional_demo", lastCheckedAt: hoursAgoIso(2), isVerified: true },
    ...input,
  };
}

function restaurant(input: Omit<Restaurant, "meta" | "externalIds"> & { externalIds?: Restaurant["externalIds"] }): Restaurant {
  return {
    externalIds: {},
    meta: { source: "fictional_demo", lastCheckedAt: hoursAgoIso(4), isVerified: true },
    ...input,
  };
}

